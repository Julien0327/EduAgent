# ---------------------------------------------------------------- 匹配逻辑

def op_kinds(equation: str) -> set[str]:
    """equation 运算特征：{'add','mul','pow'} 的子集。"""
    text = str(equation)
    kinds: set[str] = set()
    if "**" in text:
        kinds.add("pow")
    if any(c in text for c in "+-"):
        kinds.add("add")
    if any(c in text for c in "*/%"):
        kinds.add("mul")
    return kinds


def match_kps(stem_norm: str, equation: str) -> list[str]:
    """题干+算式 -> 命中的 KP 名称列表（可多个；无命中返回空表）。"""
    stem = str(stem_norm)
    kinds = op_kinds(equation)
    hits: list[str] = []
    for rule in KP_RULES:
        if rule["all"] and not all(k in stem for k in rule["all"]):
            continue
        if rule["any"] and not any(k in stem for k in rule["any"]):
            continue
        if rule["exclude"] and any(k in stem for k in rule["exclude"]):
            continue
        if rule["ops"] is not None:
            if rule["ops"] == "mixed":
                if not ("add" in kinds and "mul" in kinds):
                    continue
            elif rule["ops"] == "pow":
                if "pow" not in kinds:
                    continue
            elif rule["ops"] not in kinds:
                continue
            # ops 互斥约束：单类型规则要求另一类型不存在（一步运算口径）
            if rule["ops"] == "add" and "mul" in kinds:
                continue
            if rule["ops"] == "mul" and "add" in kinds:
                continue
        hits.append(rule["name"])
    return hits


def build_kp_id(seq: int) -> str:
    """小学 KP 编码：kp_p_<三位序号>（规则表顺序，编号冻结）。"""
    return f"kp_p_{seq:03d}"
