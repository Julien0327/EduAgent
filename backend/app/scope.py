"""学段范围守卫（Phase 3 / S0 收尾）。

当前运行时只支持小学单学段（决策㉝）。初中/更高学段请求在 API 层友好拦截：
- 不创建任务；
- 不调用 LLM；
- 不产生费用；
- 返回明确提示，引导教师使用小学内容。

检测采用“学段/年级 + 初中特有主题”的显式信号，避免把小学的“圆面积”“三角形面积”
等通用词误判为初中。
"""
from __future__ import annotations

SUPPORTED_STAGES = ("primary",)

JUNIOR_SIGNALS = (
    # 学段/年级显式信号
    "初中", "初一", "初二", "初三", "七年级", "八年级", "九年级", "中考",
    # 初中特有主题（避开“圆面积/三角形面积/方程”等小学也会出现的通用词）
    "一元二次方程", "一元一次方程", "二元一次方程", "二元一次方程组",
    "不等式", "勾股定理", "二次函数", "一次函数", "反比例函数",
    "全等三角形", "三角形全等", "相似三角形", "有理数", "整式", "分式",
    "根式", "因式分解", "平行线", "平面直角坐标系", "坐标系",
    "概率初步", "统计调查", "立方根", "实数", "科学记数法",
    "多边形内角和", "平行四边形的性质", "平行四边形的判定",
    "圆周角", "圆的切线", "弧长", "扇形面积公式",
)

SCOPE_NOTICE = (
    "当前版本聚焦小学学段，初中内容正在开发中。"
    "可以试试「分数应用题」「鸡兔同笼」或「圆的面积」等小学内容。"
)


def detect_unsupported_scope(text: str) -> str | None:
    """返回友好提示；小学/无明确初中信号返回 None。"""
    if not text:
        return None
    normalized = str(text).strip().lower()
    for signal in JUNIOR_SIGNALS:
        if signal.lower() in normalized:
            return SCOPE_NOTICE
    return None
