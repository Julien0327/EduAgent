"""P2-7A: Minimal Agent-to-Agent caller.

Provides a simple async interface to send a task-command to an external
Agent via mTLS JSON-RPC and receive the TaskResult.

Usage:
    result = await call_agent("What is 2+2?", partner_url="https://...")
    print(result.status, result.products)
"""
import asyncio
import logging
from typing import Optional

from acps_sdk.aip.aip_rpc_client import AipRpcClient
from acps_sdk.aip.aip_base_model import TaskResult

from backend.interop.rpc_client import create_rpc_client

logger = logging.getLogger(__name__)


async def call_agent(
    user_input: str,
    *,
    partner_url: Optional[str] = None,
    expected_partner_aic: Optional[str] = None,
    session_id: Optional[str] = None,
    task_id: Optional[str] = None,
    timeout: float = 60.0,
) -> TaskResult:
    """Send a task-command to an external Agent and return the TaskResult.

    Args:
        user_input: The natural-language prompt / instruction to send.
        partner_url: Target Agent RPC endpoint (overrides config).
        expected_partner_aic: Partner AIC for identity binding (overrides config).
        session_id: Optional session ID; auto-generated if omitted.
        task_id: Optional task ID; auto-generated by SDK if omitted.
        timeout: Max seconds to wait for response.

    Returns:
        TaskResult from the remote Agent.

    Raises:
        ValueError / FileNotFoundError: Config or cert issues.
        asyncio.TimeoutError: Remote Agent did not respond in time.
        Exception: Network / protocol errors propagated from SDK.
    """
    import uuid

    sid = session_id or f"sess-{uuid.uuid4()}"

    client: AipRpcClient = create_rpc_client(
        partner_url=partner_url,
        expected_partner_aic=expected_partner_aic,
    )

    try:
        logger.info(
            "Calling agent: partner=%s session=%s input=%.80s...",
            client.partner_url, sid, user_input,
        )
        result: TaskResult = await asyncio.wait_for(
            client.start_task(session_id=sid, user_input=user_input, task_id=task_id),
            timeout=timeout,
        )
        logger.info(
            "Task completed: task_id=%s status=%s products_count=%d",
            result.taskId,
            result.status,
            len(result.products) if result.products else 0,
        )
        return result
    finally:
        await client.close()


def call_agent_sync(
    user_input: str,
    **kwargs,
) -> TaskResult:
    """Synchronous wrapper for call_agent (for scripts / CLI testing)."""
    return asyncio.run(call_agent(user_input, **kwargs))
